import { Message } from "../types";

export function buildDiaryPrompt(messages: Message[], date: string): string {
  const conversation = messages
    .map((m) => `${m.role === "user" ? "사용자" : "도우미"}: ${m.content}`)
    .join("\n");

  return `아래는 오늘 하루에 대한 대화 내용입니다.

--- 대화 내용 ---
${conversation}
-----------------

위 대화를 바탕으로 오늘의 일기를 작성해주세요.

조건:
- 첫 줄에 날짜만 적으세요: ${date}
- 내가 직접 쓴 일기처럼 1인칭 구어체로 작성합니다.
- 모든 문장은 반드시 '~다' 체로 끝냅니다.
  올바른 예: "힘들었다", "창피했다", "속상했다", "그랬다", "생각났다"
  잘못된 예: "힘들었어", "창피했잖아", "속상했네", "기분이야", "떠오르네"
- '~어', '~아', '~야', '~네', '~잖아', '~요', '~습니다' 로 끝나는 문장 절대 금지.
- 자연스럽고 솔직한 구어체로 씁니다. (딱딱한 문어체 금지)
- 150~250자 분량으로 작성합니다.
- 오늘 있었던 사실과 느낀 감정을 솔직하게 담습니다.
- 억지 긍정이나 교훈적인 마무리 금지.
- 일기 외의 설명이나 코멘트는 적지 않습니다.`;
}
